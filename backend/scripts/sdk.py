"""Generate deterministic dependency-free owner client shapes from the public OpenAPI."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).parents[2]


def render(document: dict[str, Any]) -> str:
    schemas = document.get("components", {}).get("schemas", {})

    def shape(value: dict[str, Any]) -> str:
        if "$ref" in value:
            ref = value["$ref"]
            prefix = "#/components/schemas/"
            if not ref.startswith(prefix) or ref[len(prefix) :] not in schemas:
                raise ValueError("Only existing local schema references are supported")
            return "Schemas[" + json.dumps(ref[len(prefix) :]) + "]"
        for keyword, separator in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
            if keyword in value:
                return (
                    "("
                    + separator.join(dict.fromkeys(shape(item) for item in value[keyword]))
                    + ")"
                )
        if "const" in value:
            return json.dumps(value["const"], ensure_ascii=True)
        if "enum" in value:
            return (
                "("
                + " | ".join(json.dumps(item, ensure_ascii=True) for item in value["enum"])
                + ")"
            )
        kind = value.get("type")
        if isinstance(kind, list):
            return "(" + " | ".join(shape({**value, "type": item}) for item in kind) + ")"
        if kind == "array":
            return "ReadonlyArray<" + shape(value.get("items", {})) + ">"
        if kind == "object" or "properties" in value:
            properties = value.get("properties", {})
            required = set(value.get("required", []))
            members = [
                "readonly " + json.dumps(name) + (": " if name in required else "?: ") + shape(item)
                for name, item in sorted(properties.items())
            ]
            additional = value.get("additionalProperties", True)
            if isinstance(additional, dict):
                members.append(
                    "readonly [key: string]: " + ("unknown" if properties else shape(additional))
                )
            elif additional is not False:
                members.append("readonly [key: string]: unknown")
            return "{ " + "; ".join(members) + " }" if members else "Record<string, never>"
        return {
            "string": "Blob"
            if value.get("format") == "binary"
            or value.get("contentMediaType") == "application/octet-stream"
            else "string",
            "integer": "number",
            "number": "number",
            "boolean": "boolean",
            "null": "null",
        }.get(kind, "unknown")

    digest = hashlib.sha256(
        json.dumps(document, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()
    lines = [
        "/* Generated by backend/scripts/sdk.py. Server JSON Schema remains authoritative. */",
        "/* eslint-disable prettier/prettier */",
        f'export const schemaSha256 = "{digest}";',
        "export type Schemas = {",
        *[
            "  " + json.dumps(name) + ": " + shape(value) + ";"
            for name, value in sorted(schemas.items())
        ],
        "};",
        "export type Operations = {",
    ]
    descriptions: dict[str, Any] = {}
    for path, methods in sorted(document.get("paths", {}).items()):
        for method, operation in sorted(methods.items()):
            if method.upper() not in {"GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"}:
                continue
            if operation.get("x-orion-auth") == "worker":
                continue  # Native/browser owner clients are not endpoint workers.
            name = operation["operationId"]
            if name in descriptions:
                raise ValueError("Duplicate operation ID")
            if operation.get("x-orion-auth") not in {"owner", "public"}:
                raise ValueError("Operation access classification is required")
            sections = []
            for location, key in (("path", "path"), ("query", "query"), ("header", "headers")):
                parameters = [
                    item for item in operation.get("parameters", []) if item.get("in") == location
                ]
                if parameters:
                    required = any(item.get("required") for item in parameters)
                    fields = [
                        "readonly "
                        + json.dumps(item["name"])
                        + (": " if item.get("required") else "?: ")
                        + shape(item.get("schema", {}))
                        for item in parameters
                    ]
                    sections.append(
                        "readonly "
                        + key
                        + (": " if required else "?: ")
                        + "{ "
                        + "; ".join(fields)
                        + " }"
                    )
            content = operation.get("requestBody", {}).get("content", {})
            body_kind = "none"
            if content:
                media = next(
                    (
                        item
                        for item in (
                            "application/json",
                            "multipart/form-data",
                            "application/octet-stream",
                        )
                        if item in content
                    ),
                    None,
                )
                if media is None:
                    raise ValueError("Unsupported request media type")
                body_kind = {
                    "application/json": "json",
                    "multipart/form-data": "form",
                    "application/octet-stream": "binary",
                }[media]
                sections.append(
                    "readonly body"
                    + (": " if operation["requestBody"].get("required") else "?: ")
                    + shape(content[media].get("schema", {}))
                )
            success = [
                value
                for code, value in sorted(operation.get("responses", {}).items())
                if code.startswith("2")
            ]
            response = success[0] if success else {}
            media = response.get("content", {})
            response_kind, output = "empty", "void"
            if "application/json" in media:
                response_kind, output = "json", shape(media["application/json"].get("schema", {}))
            elif media:
                response_kind, output = "stream", "ReadableStream<Uint8Array>"
            lines.append(
                "  "
                + json.dumps(name)
                + ": { input: "
                + ("{ " + "; ".join(sections) + " }" if sections else "Record<string, never>")
                + "; output: "
                + output
                + " };"
            )
            descriptions[name] = {
                "method": method.upper(),
                "path": path,
                "auth": operation["x-orion-auth"],
                "body": body_kind,
                "response": response_kind,
                "headers": [
                    item["name"].lower()
                    for item in operation.get("parameters", [])
                    if item.get("in") == "header"
                ],
                "idempotentAdmission": operation.get("x-orion-idempotency") == "client_request_id",
            }
    lines.extend(
        [
            "};",
            "export const operations = "
            + json.dumps(descriptions, sort_keys=True, indent=2)
            + " as const;",
            "export type OperationId = keyof Operations;",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--schema", type=Path, default=ROOT / "ui/openapi.json")
    parser.add_argument("--output", type=Path, default=ROOT / "ui/src/lib/sdk/generated.ts")
    parser.add_argument("--write", action="store_true")
    arguments = parser.parse_args()
    document = json.loads(arguments.schema.read_text(encoding="utf-8"))
    expected = render(document)
    if arguments.write:
        arguments.output.parent.mkdir(parents=True, exist_ok=True)
        arguments.output.write_text(expected, encoding="utf-8", newline="\n")
    elif not arguments.output.exists() or arguments.output.read_text(encoding="utf-8") != expected:
        raise SystemExit("SDK contract drift: regenerate with backend/scripts/sdk.py --write")


if __name__ == "__main__":
    main()
